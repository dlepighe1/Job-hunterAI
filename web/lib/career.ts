/**
 * Career intelligence: what the user's evidence actually supports.
 *
 * This module is the product's most dangerous surface, because everything it emits is an
 * inference about somebody's career rather than a number they produced. Three rules keep it
 * honest, and each one is enforced by a test rather than by good intentions:
 *
 * 1. **Baseline analyses only.** Tailoring exists to raise a score. Feeding tailored scores
 *    back into the profile makes the system grade its own homework: it would report the user
 *    as strongest in whichever direction it most recently helped them rewrite. A user whose
 *    natural evidence supports Data Scientist at 0.81 and whose tailored resume hits 0.94
 *    has a profile built on 0.81.
 *
 * 2. **Median, not mean.** One unusual posting, written in the user's exact vocabulary or
 *    wildly mismatched, must not redefine a direction built from eighteen others.
 *
 * 3. **Say when there is not enough.** "Still learning your profile" is a real answer.
 *    Confidence is reported only where the sample supports it, and an insight nobody has
 *    the evidence for is not emitted at all.
 *
 * Pure functions over data the caller already holds. No model call, no network, because an
 * inference this consequential should be inspectable, and a sentence generated by a language
 * model about someone's career prospects is not.
 */

/** Enough analyses of one role before its median means anything. Below this it is anecdote. */
const MIN_FOR_MEDIUM_CONFIDENCE = 3;
const MIN_FOR_HIGH_CONFIDENCE = 8;
/** Enough total evidence before the product says anything about a career at all. */
const MIN_FOR_INSIGHTS = 4;

export interface BaselineAnalysis {
  /** The role the posting was for. Null when it was scored outside an application. */
  roleTitle: string | null;
  /** 0 to 1. Null for engines that do not score. */
  score: number | null;
  calibrated: boolean;
  /** False for an analysis of an already-tailored resume. Those never reach this module. */
  isBaseline: boolean;
  createdAt: string;
  missingRequirements: string[];
  coveredRequirements: string[];
}

export type Confidence = "low" | "medium" | "high";

export interface RoleAffinity {
  role: string;
  /** Median baseline score, 0 to 1. */
  affinity: number;
  confidence: Confidence;
  /** How many baseline analyses back it. Shown, because "86%" from one is not "86%". */
  sampleSize: number;
  calibratedOnly: boolean;
}

function key(role: string): string {
  return role.trim().toLowerCase();
}

/** Lower middle value for an even count, a real observation rather than a midpoint
 *  between two, which is a score no analysis produced. */
function median(values: number[]): number {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.floor((sorted.length - 1) / 2)];
}

function confidenceFor(sampleSize: number): Confidence {
  if (sampleSize >= MIN_FOR_HIGH_CONFIDENCE) return "high";
  if (sampleSize >= MIN_FOR_MEDIUM_CONFIDENCE) return "medium";
  return "low";
}

/**
 * Median baseline affinity per role, strongest first.
 *
 * Analyses with no score are dropped rather than counted as zero: the keyword and base
 * engines deliberately produce none, and treating "did not measure" as "measured badly"
 * would drag every role the user ran those engines against toward the floor.
 */
export function roleAffinities(analyses: BaselineAnalysis[]): RoleAffinity[] {
  const groups = new Map<string, { label: string; scores: number[]; calibrated: boolean[] }>();

  for (const analysis of analyses) {
    if (!analysis.isBaseline) continue;
    if (!analysis.roleTitle?.trim()) continue;
    if (analysis.score === null) continue;

    const id = key(analysis.roleTitle);
    const group = groups.get(id) ?? {
      label: analysis.roleTitle.trim(),
      scores: [],
      calibrated: [],
    };
    group.scores.push(analysis.score);
    group.calibrated.push(analysis.calibrated);
    groups.set(id, group);
  }

  return [...groups.values()]
    .map((group) => ({
      role: group.label,
      affinity: median(group.scores),
      confidence: confidenceFor(group.scores.length),
      sampleSize: group.scores.length,
      calibratedOnly: group.calibrated.every(Boolean),
    }))
    .sort((a, b) => b.affinity - a.affinity);
}

