export type InsightKind = "strength" | "gap" | "adjacency" | "pattern";

export interface Insight {
  kind: InsightKind;
  label: string;
  body: string;
}

export interface CareerInsights {
  /** False when there is not enough evidence. The UI says so instead of inventing one. */
  sufficient: boolean;
  items: Insight[];
  analysed: number;
}

/** The n most common entries in a list of requirement strings. */
function mostCommon(values: string[], limit: number): string[] {
  const counts = new Map<string, { label: string; n: number }>();
  for (const value of values) {
    const id = value.trim().toLowerCase();
    if (!id) continue;
    const entry = counts.get(id) ?? { label: value.trim(), n: 0 };
    entry.n += 1;
    counts.set(id, entry);
  }
  return [...counts.values()]
    .sort((a, b) => b.n - a.n)
    .slice(0, limit)
    .map((entry) => entry.label);
}

/**
 * Observable patterns across the user's baseline evidence.
 *
 * Every item is a claim about data in hand, phrased as an observation rather than advice.
 * There is deliberately no encouragement, no exclamation, and no forecast: this component
 * replaced a composite "pulse" score precisely because a number with no interpretation is
 * less useful than a sentence with a source.
 *
 * `declaredInterest` is what the user says they are aiming at. §76: the useful insight is
 * the GAP between that and the evidence, and the product never silently retargets them.
 */
export function careerInsights(
  analyses: BaselineAnalysis[],
  applications: { status: string; role: string }[],
  declaredInterest?: string | null,
): CareerInsights {
  const baseline = analyses.filter((analysis) => analysis.isBaseline);
  const affinities = roleAffinities(baseline);

  if (baseline.length < MIN_FOR_INSIGHTS || affinities.length === 0) {
    return { sufficient: false, items: [], analysed: baseline.length };
  }

  const items: Insight[] = [];
  const strongest = affinities[0];

  items.push({
    kind: "strength",
    label: "Strongest alignment",
    body: `Across ${strongest.sampleSize} baseline ${
      strongest.sampleSize === 1 ? "analysis" : "analyses"
    }, your resume aligns most consistently with ${strongest.role} roles (median ${Math.round(
      strongest.affinity * 100,
    )} out of 100).`,
  });

  // §76: what they want vs what the evidence supports. Stated, never acted on.
  if (declaredInterest?.trim()) {
    const declared = affinities.find((a) => key(a.role) === key(declaredInterest));
    if (declared && key(declared.role) !== key(strongest.role)) {
      items.push({
        kind: "pattern",
        label: "Target versus evidence",
        body: `You are targeting ${declaredInterest.trim()}, but your baseline analyses currently show stronger alignment with ${strongest.role}. That is a gap in the evidence, not a verdict on the goal. It points at what the resume would need to show.`,
      });
    }
  }

  const recurringGaps = mostCommon(
    baseline.flatMap((analysis) => analysis.missingRequirements),
    3,
  );
  if (recurringGaps.length > 0) {
    items.push({
      kind: "gap",
      label: "Recurring gap",
      body: `${recurringGaps.join(", ")} ${
        recurringGaps.length === 1 ? "is" : "are"
      } missing most often across the postings you have analysed. Recurring gaps cost more than one-off ones.`,
    });
  }

  const recurringStrengths = mostCommon(
    baseline.flatMap((analysis) => analysis.coveredRequirements),
    3,
  );
  if (recurringStrengths.length > 0) {
    items.push({
      kind: "strength",
      label: "Consistent evidence",
      body: `${recurringStrengths.join(", ")} ${
        recurringStrengths.length === 1 ? "is" : "are"
      } covered most reliably across those same postings.`,
    });
  }

  const adjacency = adjacentRoles(strongest.role);
  if (adjacency.length > 0) {
    const crossFunctional = adjacency.find((role) => role.category === "cross-functional");
    if (crossFunctional) {
      items.push({
        kind: "adjacency",
        label: "Adjacent direction",
        body: `${crossFunctional.role} is reachable from this evidence: ${crossFunctional.rationale.toLowerCase()}`,
      });
    }
  }

  // A pattern across applications, only when there is enough of a spread to be a pattern.
  if (applications.length >= MIN_FOR_INSIGHTS) {
    const closed = applications.filter(
      (application) => application.status === "rejected" || application.status === "withdrawn",
    ).length;
    const live = applications.length - closed;
    if (live > 0 && closed > 0) {
      items.push({
        kind: "pattern",
        label: "Pipeline",
        body: `${live} of ${applications.length} tracked applications are still open. Volume is only useful next to what it converts into, and the pipeline chart shows where they sit.`,
      });
    }
  }

  return { sufficient: true, items, analysed: baseline.length };
}
